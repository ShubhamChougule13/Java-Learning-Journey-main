public class SwitchBreakPractice {

    public static void main(String[] args) {

        int number = 1;

        switch (number) {

            case 1:
                System.out.println("One");

            case 2:
                System.out.println("Two");

            case 3:
                System.out.println("Three");

            default:
                System.out.println("Default");
        }
    }
}